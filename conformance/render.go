package conformance

import (
	"errors"
	"fmt"
	"strconv"
	"strings"
)

const (
	readmeStart      = "<!-- conformance:start -->"
	readmeEnd        = "<!-- conformance:end -->"
	gitVersionPrefix = "Git version: "
	skipNote         = "† excludes scenarios with nested .gitignore files, which this library can't load."
)

// renderTable is the agreement table shared by the README and RESULTS.md. A
// cell is n/a when the library skipped every scenario in the row, and marked
// † when it skipped some.
func renderTable(r *results) string {
	var b strings.Builder
	b.WriteString("| Feature |")
	for _, d := range r.Drivers {
		fmt.Fprintf(&b, " %s |", d.Name)
	}
	b.WriteString("\n|---|")
	for range r.Drivers {
		b.WriteString("--:|")
	}
	b.WriteString("\n")
	note := false
	for _, row := range r.Rows {
		label := row
		if row == totalRow {
			label = "**Total**"
		}
		fmt.Fprintf(&b, "| %s |", label)
		for _, c := range r.Cells[row] {
			switch {
			case c.Total == 0 && c.Skipped > 0:
				b.WriteString(" n/a |")
			case c.Skipped > 0:
				fmt.Fprintf(&b, " %d/%d † |", c.Agree, c.Total)
				note = true
			default:
				fmt.Fprintf(&b, " %d/%d |", c.Agree, c.Total)
			}
		}
		b.WriteString("\n")
	}
	if note {
		b.WriteString("\n" + skipNote + "\n")
	}
	return b.String()
}

// renderResults is conformance/RESULTS.md.
func renderResults(r *results, gitVersion string) string {
	var b strings.Builder
	b.WriteString("# Conformance results\n\n")
	b.WriteString("Generated by `make conformance-update`. Do not edit by hand.\n\n")
	b.WriteString("For each path of each scenario, every library answers whether the path is ignored, and the answer is compared with `git check-ignore --no-index`. ")
	b.WriteString("The scenarios are the curated parity cases (without the case-insensitive ones) and 300 generated scenarios from seed 1, all from `internal/paritycases`. Counts are paths.\n\n")
	b.WriteString(gitVersionPrefix + gitVersion + "\n\n")
	b.WriteString("| Library | Version | API |\n|---|---|---|\n")
	for _, d := range r.Drivers {
		fmt.Fprintf(&b, "| %s | %s | %s |\n", d.Name, d.Version, d.API)
	}
	b.WriteString("\n## Agreement\n\n")
	b.WriteString(renderTable(r))
	b.WriteString("\n## Disagreements\n")
	for i, d := range r.Drivers {
		fmt.Fprintf(&b, "\n### %s\n\n", d.Name)
		if len(r.Disagree[i]) == 0 {
			b.WriteString("None.\n")
			continue
		}
		b.WriteString("| Scenario | Files | Path | Dir | git | lib |\n|---|---|---|---|---|---|\n")
		for _, x := range r.Disagree[i] {
			b.WriteString(disagreementRow(x) + "\n")
		}
	}
	return b.String()
}

// cellEscaper keeps scenario text literal inside a markdown table cell.
var cellEscaper = strings.NewReplacer(
	`\`, `\\`, "`", "\\`", "*", `\*`, "_", `\_`, "[", `\[`, "]", `\]`,
	"<", `\<`, ">", `\>`, "|", `\|`, "~", `\~`, "\n", " ",
)

func disagreementRow(d disagreement) string {
	lib := strconv.FormatBool(d.Lib)
	if d.Err != "" {
		lib = "error: " + d.Err
	}
	cells := []string{
		d.Scenario,
		formatFiles(d.Files),
		strconv.Quote(d.Path),
		strconv.FormatBool(d.IsDir),
		strconv.FormatBool(d.Git),
		lib,
	}
	for i, c := range cells {
		cells[i] = cellEscaper.Replace(c)
	}
	return "| " + strings.Join(cells, " | ") + " |"
}

// stripGitVersion drops the git version line, which differs between machines
// and CI without any change in the verdicts.
func stripGitVersion(s string) string {
	var out []string
	for line := range strings.SplitSeq(s, "\n") {
		if !strings.HasPrefix(line, gitVersionPrefix) {
			out = append(out, line)
		}
	}
	return strings.Join(out, "\n")
}

// spliceReadme replaces what is between the conformance markers with table.
func spliceReadme(readme, table string) (string, error) {
	if strings.Count(readme, readmeStart) != 1 || strings.Count(readme, readmeEnd) != 1 {
		return "", errors.New("README.md needs exactly one " + readmeStart + " and one " + readmeEnd)
	}
	start := strings.Index(readme, readmeStart) + len(readmeStart)
	end := strings.Index(readme, readmeEnd)
	if end < start {
		return "", errors.New("README.md has " + readmeEnd + " before " + readmeStart)
	}
	return readme[:start] + "\n" + table + readme[end:], nil
}
